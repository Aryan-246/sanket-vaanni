import React, { useEffect, useRef } from 'react';
import { Animated, Easing, ScrollView, StyleSheet, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { ActionButton } from '../components/ActionButton';
import { AppText } from '../components/AppText';
import { Badge } from '../components/Badge';
import { Card } from '../components/Card';
import { FlexBar } from '../components/FlexBar';
import { StatusPill, type StatusKind } from '../components/StatusPill';
import { useAppState } from '../app/AppState';
import { FINGERS } from '../sensors/types';
import { flexMagnitude } from '../sensors/processing';
import { colors, letterSpacing, radii, spacing } from '../theme';

export interface HomeScreenProps {
  onOpenSettings: () => void;
}

export function HomeScreen({ onOpenSettings }: HomeScreenProps): React.JSX.Element {
  const insets = useSafeAreaInsets();
  const {
    status,
    sample,
    isDemo,
    recognitionAvailable,
    recognitionUnavailableReason,
  } = useAppState();

  const entrance = useRef(new Animated.Value(0)).current;

  useEffect(() => {
    Animated.timing(entrance, {
      toValue: 1,
      duration: 420,
      easing: Easing.out(Easing.cubic),
      useNativeDriver: true,
    }).start();
  }, [entrance]);

  const enterStyle = {
    opacity: entrance,
    transform: [
      { translateY: entrance.interpolate({ inputRange: [0, 1], outputRange: [12, 0] }) },
    ],
  };

  const connected = status.kind === 'connected';
  const pill: { kind: StatusKind; label: string } = (() => {
    switch (status.kind) {
      case 'connected':
        return { kind: isDemo ? 'demo' : 'connected', label: isDemo ? 'Demo data' : 'Connected' };
      case 'connecting':
        return { kind: 'idle', label: 'Connecting…' };
      case 'scanning':
        return { kind: 'idle', label: 'Scanning…' };
      case 'disconnected':
        return { kind: 'idle', label: 'Disconnected' };
      case 'error':
        return { kind: 'error', label: 'Error' };
      case 'unavailable':
        return { kind: 'unavailable', label: 'Not available' };
      default:
        return { kind: 'idle', label: 'Idle' };
    }
  })();

  const activity = sample ? flexMagnitude(sample.flex) : 0;

  return (
    <ScrollView
      style={styles.root}
      contentContainerStyle={[
        styles.content,
        { paddingTop: insets.top + spacing.lg, paddingBottom: insets.bottom + spacing.xxl },
      ]}
      showsVerticalScrollIndicator={false}
    >
      <Animated.View style={enterStyle}>
        <View style={styles.header}>
          <View style={styles.headerRow}>
            <View style={styles.brandBlock}>
              <AppText variant="display" style={styles.wordmark}>
                संकेत वाणी
              </AppText>
              <AppText variant="overline" color={colors.textMuted} overline>
                Sign · Speech
              </AppText>
            </View>
            <ActionButton
              label="Settings"
              tone="ghost"
              accessibilityHint="Opens settings, including replaying the intro"
              onPress={onOpenSettings}
              style={styles.settingsButton}
            />
          </View>
        </View>

        {/* --- Connection ------------------------------------------------ */}
        <Card style={styles.section}>
          <View style={styles.sectionHead}>
            <AppText variant="overline" color={colors.textMuted} overline>
              Glove link
            </AppText>
            <StatusPill kind={pill.kind} label={pill.label} />
          </View>

          {isDemo && (
            <Badge
              tone="demo"
              label="Demo mode · simulated"
              style={styles.demoBadge}
            />
          )}

          <AppText variant="body" color={colors.textSecondary} style={styles.sectionBody}>
            {isDemo
              ? 'Readings below are generated by the built-in simulator. No glove is connected and no Bluetooth is in use.'
              : 'Bluetooth glove support is not implemented yet. The firmware protocol has not been verified.'}
          </AppText>
        </Card>

        {/* --- Live signals ---------------------------------------------- */}
        <Card style={styles.section}>
          <View style={styles.sectionHead}>
            <AppText variant="overline" color={colors.textMuted} overline>
              Flex channels · right hand
            </AppText>
            {isDemo && <Badge tone="demo" label="Simulated" />}
          </View>

          <View style={styles.bars}>
            {FINGERS.map((finger, index) => (
              <FlexBar
                key={finger}
                label={finger}
                value={sample ? (sample.flex[index] ?? 0) : 0}
              />
            ))}
          </View>

          <View
            style={styles.activityRow}
            accessible
            accessibilityLabel={`Overall flexion ${(activity * 100).toFixed(0)} percent`}
          >
            <AppText variant="caption" color={colors.textMuted}>
              Overall flexion
            </AppText>
            <AppText variant="label" color={colors.accent}>
              {(activity * 100).toFixed(0)}%
            </AppText>
          </View>

          {!connected && (
            <AppText variant="caption" color={colors.textMuted} style={styles.quietNote}>
              Start the simulator to see values move.
            </AppText>
          )}
        </Card>

        {/* --- Recognition ----------------------------------------------- */}
        <Card style={styles.section}>
          <View style={styles.sectionHead}>
            <AppText variant="overline" color={colors.textMuted} overline>
              Recognised sign
            </AppText>
            <Badge tone="neutral" label="Not implemented" />
          </View>
          <AppText variant="heading" color={colors.textMuted} style={styles.sectionBody}>
            —
          </AppText>
          <AppText variant="caption" color={colors.textMuted}>
            {recognitionAvailable
              ? 'A recognition model is available.'
              : (recognitionUnavailableReason ??
                'Recognition is not implemented yet.')}
          </AppText>
        </Card>

        {/* --- History ---------------------------------------------------- */}
        <Card style={styles.section}>
          <AppText variant="overline" color={colors.textMuted} overline>
            Recent history
          </AppText>
          <AppText variant="body" color={colors.textMuted} style={styles.sectionBody}>
            Nothing yet. History will fill as signs are recognised, and it is stored
            on this device only.
          </AppText>
        </Card>

        <AppText variant="caption" color={colors.textMuted} center style={styles.footer}>
          Foundation build · no glove connection, no recognition, no speech
        </AppText>
      </Animated.View>
    </ScrollView>
  );
}

const styles = StyleSheet.create({
  root: {
    flex: 1,
    backgroundColor: colors.background,
  },
  content: {
    paddingHorizontal: spacing.lg,
    gap: spacing.md,
  },
  header: {
    marginBottom: spacing.sm,
  },
  headerRow: {
    flexDirection: 'row',
    alignItems: 'flex-start',
    justifyContent: 'space-between',
  },
  brandBlock: {
    flexShrink: 1,
    gap: spacing.xs,
  },
  wordmark: {
    letterSpacing: letterSpacing.tight,
  },
  settingsButton: {
    paddingHorizontal: spacing.lg,
    minHeight: 40,
  },
  section: {
    gap: spacing.sm,
  },
  sectionHead: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'space-between',
    gap: spacing.sm,
  },
  sectionBody: {
    marginTop: spacing.xs,
  },
  demoBadge: {
    marginTop: spacing.xs,
  },
  bars: {
    flexDirection: 'row',
    gap: spacing.sm,
    marginTop: spacing.md,
  },
  activityRow: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    alignItems: 'center',
    marginTop: spacing.lg,
    paddingTop: spacing.md,
    borderTopWidth: StyleSheet.hairlineWidth,
    borderTopColor: colors.border,
  },
  quietNote: {
    marginTop: spacing.xs,
  },
  footer: {
    marginTop: spacing.lg,
    paddingHorizontal: spacing.lg,
  },
  divider: {
    height: radii.sm,
  },
});
