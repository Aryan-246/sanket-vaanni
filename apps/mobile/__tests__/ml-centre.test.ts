/* ------------------------------------------------------------------ harness */

/** A frame producer a test cranks by hand. The only thing `MlCentre` needs. */
interface Crank {
  readonly source: FrameSource;
  emit(samples: readonly SensorSample[]): void;
  listenerCount(): number;
}

function crank(): Crank {
  const listeners = new Set<(sample: SensorSample) => void>();
  return {
    source: {
      onFrame(listener) {
        listeners.add(listener);
        return () => {
          listeners.delete(listener);
        };
      },
    },
    emit(samples) {
      for (const sample of samples) {
        for (const listener of listeners) listener(sample);
      }
    },
    listenerCount: () => listeners.size,
  };
}

/** Lets every pending microtask run — a storage write, a fire-and-forget save. */
async function settle(times = 4): Promise<void> {
  for (let index = 0; index < times; index += 1) await Promise.resolve();
}

interface CentreHarness {
  readonly centre: MlCentre;
  readonly right: Crank;
  readonly left: Crank;
  setGlove(info: GloveInfo): void;
}

async function makeCentre(): Promise<CentreHarness> {
  const right = crank();
  const left = crank();
  let glove: GloveInfo = {
    connected: true,
    real: false,
    transportName: 'Demo Mode (simulated)',
    calibrationVersion: 1,
  };
  let counter = 0;

  const centre = new MlCentre({
    storage: createInMemoryStorage(),
    newId: () => `id-${(counter += 1)}`,
    now: () => 1_700_000_000_000,
    defaultLanguageId: 'isl',
    sources: { left: left.source, right: right.source },
    gloveInfo: () => glove,
    picker: new UnavailablePicker(),
  });

  await centre.start();
  return {
    centre,
    right,
    left,
    setGlove: (info) => {
      glove = info;
    },
  };
}

/* ------------------------------------------------------------------- cases */

describe('MlCentre — what it refuses, and what it records', () => {
  it('will not open a session when nothing is connected, and says what to do', async () => {
    const harness = await makeCentre();
    harness.setGlove({
      connected: false,
      real: false,
      transportName: 'None',
      calibrationVersion: null,
    });

    const outcome = await harness.centre.beginCapture({ side: 'right', handContext: 'right' });

    expect(outcome.ok).toBe(false);
    if (outcome.ok) throw new Error('unreachable');
    // The sentence has to name the actual obstacle and the way past it, not
    // "error" — recording with no frames would produce an empty session.
    expect(outcome.reason).toContain('No glove is connected');
    expect(outcome.reason).toContain('Demo Mode');
    expect(harness.centre.capture.getSnapshot().session).toBeNull();

    harness.centre.dispose();
  });

  it('records a window from a simulated source as simulated, not as a glove', async () => {
    const harness = await makeCentre();
    const { centre, right } = harness;

    await centre.store.createLabel('Namaste', null);
    expect((await centre.beginCapture({ side: 'right', handContext: 'right' })).ok).toBe(true);

    /*
     * A window has to be started before its frames mean anything: the recorder
     * ignores samples between windows, so emitting without this would leave the
     * buffer empty and the build would refuse for having too few readings — which
     * is the behaviour the next case checks on purpose.
     */
    expect(centre.capture.beginWindow().ok).toBe(true);
    right.emit(makeRun('Namaste', 1000));
    await settle();

    // The window completed on its own: the recorder watches the timestamps of the
    // frames that arrived rather than a timer, so this is the real end of a run.
    expect(centre.capture.getSnapshot().phase).toBe('awaiting-label');

    const confirmed = await centre.capture.confirm(centre.store.getSnapshot().labels[0]!.id);
    expect(confirmed.ok).toBe(true);
    await settle();

    const summary = centre.store.summary();
    expect(summary.approved).toBe(1);
    expect(summary.pending).toBe(0);

    /*
     * Provenance is the point. `sourceFor` reads it from the transport, so a
     * session recorded through the Demo Mode producer has to say so in its own
     * record — the split, the activation gate and the model card all read it.
     */
    const session = centre.store.getSnapshot().sessions[0]!;
    expect(session.source).toBe('simulated');
    expect(session.deviceLabel).toBe('Demo Mode (simulated)');

    const header = centre.store.getSnapshot().headers[0]!;
    expect(header.source).toBe('simulated');
    expect(header.approval).toBe('approved');
    expect(header.quality.frameCount).toBeGreaterThan(0);

    centre.dispose();
  });

  it('keeps an unlabelled window out of the approved count', async () => {
    const harness = await makeCentre();
    const { centre, right } = harness;

    await centre.store.createLabel('Namaste', null);
    await centre.beginCapture({ side: 'right', handContext: 'right' });
    centre.capture.beginWindow();
    right.emit(makeRun('Namaste', 1000));
    await settle();

    // "I am not sure what I just did" is a first-class answer: the motion is
    // kept, the window is not a training example.
    const confirmed = await centre.capture.confirm(null);
    expect(confirmed.ok).toBe(true);
    await settle();

    const summary = centre.store.summary();
    expect(summary.total).toBe(1);
    expect(summary.approved).toBe(0);
    expect(summary.pending).toBe(1);

    centre.dispose();
  });

  it('stops holding frames for live evaluation when live updates are off', async () => {
    const harness = await makeCentre();
    const { centre, right } = harness;

    centre.setLiveUpdates(true);
    right.emit(makeRun('sign-a', 0));
    await settle();
    expect(centre.getSnapshot().inference.buffered).toBeGreaterThan(0);

    /*
     * With no model there is nothing to name, and the screen says so rather than
     * scoring something. The reason is a code here and a sentence on screen.
     */
    const outcome = centre.getSnapshot().inference.outcome;
    expect(outcome.kind).toBe('unknown');
    if (outcome.kind !== 'unknown') throw new Error('unreachable');
    expect(outcome.reason).toBe('no-model');

    centre.setLiveUpdates(false);
    // Cleared, so a reading from minutes ago is never presented as the current one.
    expect(centre.getSnapshot().inference.buffered).toBe(0);
    expect(centre.getSnapshot().inference.receiving).toBe(false);

    centre.dispose();
  });

  it('refuses to train without permission, and writes no model', async () => {
    const harness = await makeCentre();
    const { centre, right } = harness;

    await centre.store.createLabel('A', null);
    await centre.store.createLabel('B', null);
    await centre.beginCapture({ side: 'right', handContext: 'right' });

    // One confirmed window of each sign, recorded in one session.
    for (const sign of ['A', 'B'] as const) {
      centre.capture.beginWindow();
      right.emit(makeRun(sign, 1_000));
      await settle();
      await centre.capture.confirm(centre.store.getSnapshot().labels.find((l) => l.text === sign)!.id);
      await settle();
    }

    // Consent to record is not consent to train, so this must refuse.
    const refused = await centre.train();
    expect(refused.ok).toBe(false);
    if (refused.ok) throw new Error('unreachable');
    expect(refused.reason.length).toBeGreaterThan(0);

    // Nothing was written, so there is no half-trained version left behind.
    expect(centre.store.getSnapshot().models).toHaveLength(0);
    expect(centre.getSnapshot().activeModel).toBeNull();

    centre.dispose();
  });
});

describe('the learning centre is an administrative surface', () => {
  /*
   * This block used to assert the opposite.
   *
   * It navigated Settings → "Models and vocabulary" as a guest and required the
   * learning centre to open. That was the behaviour, and the behaviour was
   * wrong: everything on the screen — recording, labelling, fitting, activating,
   * deleting — is a privileged operation over state the app treats as the
   * device's own training set. A guest could reach all of it from Settings with
   * two taps.
   *
   * The route is now gated on the account's role and the entry point has moved
   * to the administration console. These cases pin both halves, because either
   * one alone is not a gate: hiding the row while leaving the route open is
   * security by absence, and gating the route while leaving the row drawn shows
   * a door that does not open.
   */
  it('is no longer offered anywhere in an ordinary user’s Settings', async () => {
    const { renderer } = await renderApp({ skipIntro: true });

    await pressByLabel(renderer, 'Settings');
    await flush();

    const settings = renderedText(renderer);

    // The row is gone, not merely disabled.
    expect(has(renderer, 'models-row')).toBe(false);
    expect(settings).not.toContain('Models and vocabulary');
    // The whole section it lived under is gone with it, rather than being left
    // behind as an empty heading.
    expect(settings).not.toContain('What the glove is read against');

    // And the console is not offered either, because this session is a guest.
    // The two rows are gated by the same rule, so this also catches a
    // regression that would offer one without the other.
    expect(has(renderer, 'admin-row')).toBe(false);

    await teardown(renderer);
  });

  it('does not render at a route a guest can reach', async () => {
    /*
     * The stronger half, and the one the previous version of this file could not
     * make. The bundle is public, so a screen is not protected by being hard to
     * find — but a route that renders for anyone who asks is not gated at all.
     *
     * This case therefore pushes the route *directly* and asserts nothing is
     * drawn. It is the only form of the question that has a failure mode: the
     * earlier draft navigated to the screen, which passes whether the gate is
     * there or not, because the gate removes the navigation that the test used.
     */
    const { renderer } = await renderApp({ skipIntro: true, initialDetail: 'ml' });

    await flush();

    expect(has(renderer, 'ml-screen')).toBe(false);
    const text = renderedText(renderer);
    expect(text).not.toContain('Where frames come from');
    expect(text).not.toContain('Train a version');
    expect(text).not.toContain('No part of this is a cloud backup.');

    await teardown(renderer);
  });

  /*
   * What this block does *not* cover, stated so it is not mistaken for covered:
   * the console's own rendering of the learning entry. `AccountProvider` has no
   * seam for injecting a profile, so no existing test can render the app as an
   * administrator — `__tests__` contains no case that mounts `AdminScreen` at
   * all. The console's half of the gate is therefore held in place by the type
   * of its prop (`onOpenMl?: () => void`) and by `RootNavigator` passing it only
   * under `canOpenAdmin`, not by a test.
   */
});

/* ------------------------------------------------------------------- studio */

/**
 * The learning centre on its own, in the providers it actually needs.
 *
 * The screen is no longer reachable by tapping, so it can no longer be tested by
 * tapping. Mounting it directly keeps the coverage that matters — what each area
 * says when the phone holds nothing — while the block above covers the gate. The
 * two together are what the navigation case used to claim on its own.
 *
 * `AppStateProvider` supplies the real `MlCentre`, `FrameSource` and calibration
 * state; the default transports are the app's own simulators, so nothing is
 * stubbed that the shipped build would not also have.
 */
async function renderStudio(): Promise<ReactTestRenderer.ReactTestRenderer> {
  return renderThemed(
    React.createElement(AppStateProvider, {
      storage: createInMemoryStorage(),
      children: React.createElement(MlScreen, { onClose: () => undefined }),
    }),
  );
}

describe('the learning centre, as the console opens it', () => {
  it('offers the five areas, each one press away', async () => {
    const renderer = await renderStudio();

    const overview = renderedText(renderer);
    for (const label of ['Overview', 'Record', 'Library', 'Models', 'Live']) {
      expect(overview).toContain(label);
    }
    expect(overview).toContain('Where frames come from');
    expect(overview).toContain('Nothing on this list may overstate what works.');

    await teardown(renderer);
  });

  it('shows the Models area with no fabricated figure and no fabricated version', async () => {
    const renderer = await renderStudio();

    await pressByLabel(renderer, 'Models');
    await flush();

    const text = renderedText(renderer);
    expect(text).toContain('Train a version');
    expect(text).toContain('No model has been trained');
    // With no consent given, the run is refused before it starts, and the screen
    // says why rather than offering a button that would fail.
    expect(text).toContain('Training is off');
    // Nothing here may state a figure that no artefact supports.
    expect(text).not.toMatch(/\d+(\.\d+)?% of held-out/);

    await teardown(renderer);
  });

  it('says the Live area is not naming a sign when no model is in use', async () => {
    const renderer = await renderStudio();

    await pressByLabel(renderer, 'Live');
    await flush();

    const text = renderedText(renderer);
    expect(text).toContain('It is not naming a sign');
    /*
     * With no frames arriving at all the buffer is empty, so the refusal is
     * `unusable-window` rather than `no-model` — the screen checks the window
     * before it consults a model, and says the window could not be read. The
     * honest claim to pin is that it names no sign and states what is missing,
     * whichever of the two reasons the current state produces.
     */
    expect(text).toContain('No model has been trained on this phone yet.');
    // The thresholds are the user's own and are not calibrated, and the screen
    // says so where a reader will see it.
    expect(text).toContain('These are thresholds, not confidences.');

    await teardown(renderer);
  });

  it('keeps photos and video on their own pipeline in the Library area', async () => {
    const renderer = await renderStudio();

    await pressByLabel(renderer, 'Library');
    await flush();

    const text = renderedText(renderer);
    expect(text).toContain('Signs');
    expect(text).toContain('Photos and video');
    // Storing a photo never trains the glove model, and the screen says so.
    expect(text).toContain(VISION_NOTE);
    // And export is not cloud backup, in those words.
    expect(text).toContain('No part of this is a cloud backup.');

    await teardown(renderer);
  });

  it('offers the Record area, which asks which glove and which hand', async () => {
    const renderer = await renderStudio();

    await pressByLabel(renderer, 'Record');
    await flush();

    const text = renderedText(renderer);
    expect(text).toContain('Start a session');
    expect(text).toContain('Which glove are you recording from?');
    expect(text).toContain('Which hand are you signing with?');
    // The hand context is what the user states, never read off the motion.
    expect(text).toContain('not something read off the motion');

    await teardown(renderer);
  });

  it('offers to carry a version to another phone, and says there is no catalogue', async () => {
    const renderer = await renderStudio();

    await pressByLabel(renderer, 'Library');
    await flush();

    const text = renderedText(renderer);
    expect(text).toContain('Versions on other phones');
    // The limitation is stated, not implied: this is not a model store.
    expect(text).toContain('There is no shared catalogue and no server holding versions.');
    // Nothing has been trained, so there is nothing to carry out: the screen
    // explains that, and the button that would do it is not pressable.
    expect(has(renderer, 'carry-none')).toBe(true);
    expect(isDisabled(renderer, 'carry-out')).toBe(true);

    await teardown(renderer);
  });

  it('refuses to take a version in when the clipboard cannot be read', async () => {
    /*
     * On this platform there is no native module behind the clipboard, so the
     * read returns null. The honest outcome is a statement that it could not be
     * read — never a claim that nothing was found, and never a silent no-op.
     */
    const renderer = await renderStudio();

    await pressByLabel(renderer, 'Library');
    await flush();
    expect(isDisabled(renderer, 'carry-in')).toBe(false);
    await pressByTestId(renderer, 'carry-in');
    await flush();

    const text = renderedText(renderer);
    expect(text).toContain('The clipboard could not be read in this build');
    expect(has(renderer, 'carry-error')).toBe(true);
    // Nothing was stored, so nothing new is claimed to exist.
    expect(has(renderer, 'carry-pick-1')).toBe(false);

    await teardown(renderer);
  });
});
